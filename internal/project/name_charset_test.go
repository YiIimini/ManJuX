package project

import "testing"

// 技能侧 2026-09-28 通知：章名/书名**只准全角标点，禁一切 ASCII 标点与空格**。
//
// 平台此前只允许 中文/字母/数字/_/-/· ⇒ 盘上出现平台**替技能侧改字**：
//
//	《补碑人改命，守钟英逆时》 → 目录名 `补碑人改命·守钟女逆时`（全角逗号变间隔号）
//	章名「她替他挡账（二）」   → 会被改成「她替他挡账·二」
//
// 而技能侧明确要求"不要静默替换"（章名就是集名，改字会让成片与集号记录对不上）。
// 既然他们保证章名/书名里不会出现 ASCII 标点与空格，平台就该照原样放行全角。
func TestProjectNameAcceptsFullWidthPunctuation(t *testing.T) {
	ok := []string{
		"补碑人改命，守钟女逆时",               // 真书名（盘上曾被改成 ·）
		"补碑人改命，守钟女逆时·第45集·她替他挡账（二）", // 真章名带全角括号
		"求你们骂我·第02集·骂人一处，现钱五文",      // 用户实测过的那个标题
		"书名·第01集·碑上写我死了",
		"《书名》·第1集·「引号」",
		"停顿、顿号；分号：冒号！叹号？问号。句号",
	}
	for _, n := range ok {
		if !ValidProjectName(n) {
			t.Errorf("技能侧合规的名字必须放行，实际被判非法: %q", n)
		}
	}
	// ASCII 标点与空格仍然一律拒（技能侧同样禁止；且它们是文件系统/导出分隔符的风险源）
	bad := []string{
		"书名 · 第1集", // 空格
		"章名,带半角逗号", // 半角逗号
		"章名:冒号",    // 半角冒号（NTFS ADS 陷阱）
		"章名{块}",    // 花括号（ASS 覆写块）
		"a/b", "a\\b", "a*b", "a?b", "a\"b", "a<b", "a>b", "a|b",
		"trailing.", "tab\there", // 结尾句点、制表符
	}
	for _, n := range bad {
		if ValidProjectName(n) {
			t.Errorf("ASCII 标点/空格/控制字符必须拒，实际被判合法: %q", n)
		}
	}
}
