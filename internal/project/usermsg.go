package project

import "fmt"

// usermsg.go 用户可见错误的**统一出口**。
//
// ## 为什么需要这个文件（2026-09-29 代码健康审计 P1-6）
//
// 同一件事在不同端点各报各的，用户看到的是"同一台软件在不同地方说不同的话"：
//
//	「项目运行中」（409）—— 4 种文案、10 处：
//	  · "项目正在运行中,请先停止"（pipeline）
//	  · "项目运行中,请先停止"（server，7 处）
//	  · "项目运行中,不能调参"（个别端点）
//	  · **"项目运行中"** —— 连"请先停止"都不给（handlers_shot.go:230）
//	「尚无分镜方案」（404）—— 2 种文案、12 处，而**只有两处**告诉用户该做什么
//	  （`stages_render.go` / `stages_assets.go` 的"请先运行「剧本分镜」阶段"），
//	  其余让用户自己猜。
//
// 后果不只是难看：前端**无法用稳定字符串识别"项目在跑"**来做引导（现在只能靠 409 猜），
// 而"该干什么"这件事恰好是用户最需要的下一步动作。
//
// 所以两条都收口到这里，文案里**带上下一步动作**。
// 判定之外的地方（比如 HTTP 状态码）仍由调用方决定 —— 这里只管"说什么"。

// ErrProjectRunning 项目正在跑（HTTP 409）。
//
// 传 phase 说明"在跑哪个阶段"（可为空）——用户看到具体阶段才知道该等还是该停。
func ErrProjectRunning(phase string) error {
	if phase == "" {
		return fmt.Errorf("项目正在运行中 —— 请先点「停止」，等它收完尾再操作")
	}
	return fmt.Errorf("项目正在运行中（当前阶段：%s）—— 请先点「停止」，等它收完尾再操作", phase)
}

// ErrNoPlan 还没有分镜方案（HTTP 404）。
//
// **必须带上"该去点哪里"**：这是用户最需要的信息，而 12 处调用点里此前只有 2 处写了。
func ErrNoPlan() error {
	return fmt.Errorf("尚未生成分镜方案 —— 请先运行「剧本分镜」阶段")
}

// ErrCleanupBusy 一键清理时还有管线在跑（用于"某项故意没清"的说明）。
func ErrCleanupBusy(what string) string {
	return what + "：**本机还有管线在跑**，那里可能有正在用的中间产物 —— 等它跑完再清"
}
